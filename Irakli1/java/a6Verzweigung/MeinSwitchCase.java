public class MeinSwitchCase {
   
   
    public static void main(String[] args) {
       
       //Eingabe
        int auswahl = 1;

        //Verarbeitung
        switch (auswahl) {
            case 0: System.out.println("auswahl = 0");
            break;

            case 1: System.out.println("auswahl = 1");
            break;    
        
            default:
            System.out.println("Es wurde keine auswahl getroffen");
                break;
        }

        
    //Ausgabe

    System.out.println("Progammende");

    }
    
}
